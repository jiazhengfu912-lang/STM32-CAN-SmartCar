#define BOOT_META_BASE  0x0800F800U
#define BOOT_PARAM_BASE 0x0800FC00U
#define BOOT_RAM_BASE   0x20000000U
#define BOOT_RAM_LIMIT  0x20005000U
#define BOOT_META_SIZE 32U
#define BOOT_MAGIC 0x3141544FU
#define BOOT_FORMAT 1U
#define BOOT_COMMITTED 0xA55A3CC3U

#endif
